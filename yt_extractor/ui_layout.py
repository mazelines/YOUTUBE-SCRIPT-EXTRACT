from PySide6.QtCore import Qt
from PySide6.QtGui import QKeySequence, QShortcut
from PySide6.QtWidgets import (
    QWidget, QFrame, QLabel, QPushButton, QVBoxLayout, QHBoxLayout,
    QFormLayout, QPlainTextEdit, QLineEdit, QCheckBox, QComboBox, QSpinBox,
    QButtonGroup, QGroupBox, QDialog, QScrollArea, QDialogButtonBox,
    QTableWidget, QHeaderView, QAbstractItemView, QStackedWidget,
    QProgressBar, QDockWidget,
)
from . import __version__


def label(text, role="muted"):
    widget = QLabel(text)
    widget.setObjectName(role)
    widget.setTextFormat(Qt.PlainText)
    return widget


def button(text, slot, role=None):
    widget = QPushButton(text)
    if role:
        widget.setObjectName(role)
    widget.clicked.connect(slot)
    return widget


def card():
    widget = QFrame()
    widget.setObjectName("card")
    layout = QVBoxLayout(widget)
    layout.setContentsMargins(16, 12, 16, 12)
    layout.setSpacing(8)
    return widget, layout


def build_settings(w):
    w.settings_dialog = QDialog(w)
    w.settings_dialog.setWindowTitle("고급 설정")
    w.settings_dialog.resize(560, 620)
    outer = QVBoxLayout(w.settings_dialog)
    outer.addWidget(label("추출 방식을 설정하세요", "sectionTitle"))
    outer.addWidget(label("변경한 값은 다음 작업부터 적용됩니다."))
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    content = QWidget()
    layout = QVBoxLayout(content)
    layout.setContentsMargins(0, 0, 8, 0)
    scroll.setWidget(content)
    outer.addWidget(scroll, 1)

    group = QGroupBox("자막")
    form = QFormLayout(group)
    form.setSpacing(12)
    w.lang_input = QLineEdit("ko, en")
    w.lang_input.setToolTip("쉼표로 구분한 언어 코드 우선순위 (예: ko, en, ja)")
    form.addRow("선호 언어", w.lang_input)
    w.manual_cb = QCheckBox("수동 자막 우선")
    w.manual_cb.setChecked(True)
    form.addRow(w.manual_cb)
    formats = QWidget()
    row = QHBoxLayout(formats)
    row.setContentsMargins(0, 0, 0, 0)
    w._fmt_group = QButtonGroup(w)
    for attr, title in (("_fmt_sentence", "문장"), ("_fmt_paragraph", "단락"),
                        ("_fmt_timestamp", "타임스탬프")):
        b = QPushButton(title)
        b.setCheckable(True)
        w._fmt_group.addButton(b)
        setattr(w, attr, b)
        row.addWidget(b)
    w._fmt_sentence.setChecked(True)
    form.addRow("Markdown 형식", formats)
    w.translate_cb = QCheckBox("한국어 번역도 저장 (.ko.md)")
    w.translate_cb.setToolTip("YouTube 번역 자막을 함께 저장합니다. AI 전체 번역도 완료 시 자동 저장합니다.")
    form.addRow(w.translate_cb)
    layout.addWidget(group)

    group = QGroupBox("자막이 없는 영상 · 라이브")
    form = QFormLayout(group)
    form.setSpacing(12)
    w.stt_cb = QCheckBox("음성 인식으로 자막 생성 (Whisper)")
    w.stt_cb.setToolTip("자막이 없으면 음성을 내려받아 텍스트로 변환합니다. 첫 사용 시 모델을 다운로드합니다.")
    form.addRow(w.stt_cb)
    w.stt_hint = label("음성 인식 사용 가능 여부 확인 중…")
    w.stt_hint.setWordWrap(True)
    form.addRow(w.stt_hint)
    w.stt_model_combo = QComboBox()
    w.stt_model_combo.addItems(["tiny (빠름)", "base", "small (권장)", "medium", "large-v3 (정확)"])
    w.stt_model_combo.setCurrentIndex(2)
    form.addRow("음성 인식 모델", w.stt_model_combo)
    w.stt_live_spin = QSpinBox()
    w.stt_live_spin.setRange(0, 480)
    w.stt_live_spin.setValue(60)
    w.stt_live_spin.setSuffix(" 분")
    w.stt_live_spin.setToolTip("수신한 라이브 스트림을 지정한 시간만큼 녹음합니다. 0이면 라이브 음성 인식을 건너뜁니다.")
    form.addRow("라이브 수집 시간", w.stt_live_spin)
    w.stt_poll_spin = QSpinBox()
    w.stt_poll_spin.setRange(0, 180)
    w.stt_poll_spin.setSuffix(" 분")
    w.stt_poll_spin.setSpecialValueText("대기 안 함")
    w.stt_poll_spin.setToolTip("YouTube 자막이 생성되기를 기다리는 최대 시간입니다. 음성 인식과 독립적으로 동작합니다.")
    form.addRow("YouTube 자막 대기", w.stt_poll_spin)
    layout.addWidget(group)
    group = QGroupBox("작업")
    form = QFormLayout(group)
    w.concurrency = QSpinBox()
    w.concurrency.setRange(1, 16)
    w.concurrency.setValue(4)
    form.addRow("동시 작업 수", w.concurrency)
    layout.addWidget(group)
    layout.addStretch()
    close = QDialogButtonBox(QDialogButtonBox.Close)
    close.button(QDialogButtonBox.Close).setText("설정 닫기")
    close.rejected.connect(w.settings_dialog.reject)
    outer.addWidget(close)
    # Settings are live widget values: closing the dialog never resets them.
    for signal in (w.lang_input.textChanged, w.concurrency.valueChanged,
                   w.manual_cb.toggled, w.translate_cb.toggled, w.stt_cb.toggled,
                   w.stt_poll_spin.valueChanged, w.stt_live_spin.valueChanged,
                   w.stt_model_combo.currentIndexChanged, w._fmt_group.buttonToggled):
        signal.connect(w._update_settings_summary)


def build_workspace(w, chat_class, banner_class):
    w._paths_by_job = {}
    w._next_job_id = 0
    central = QWidget()
    central.setObjectName("workspace")
    viewport = QScrollArea()
    viewport.setWidgetResizable(True)
    viewport.setWidget(central)
    w.setCentralWidget(viewport)
    root = QVBoxLayout(central)
    root.setContentsMargins(24, 20, 24, 8)
    root.setSpacing(12)

    header = QHBoxLayout()
    heading = QVBoxLayout()
    heading.setSpacing(3)
    heading.addWidget(label("MAZELINE  /  VIDEO TO TEXT", "eyebrow"))
    heading.addWidget(label("YouTube 자막 추출기", "pageTitle"))
    heading.addWidget(label("영상에서 필요한 내용을, 하나의 작업 공간에서."))
    header.addLayout(heading, 1)
    header.addWidget(label(f"v{__version__}", "badge"), 0, Qt.AlignVCenter)
    w.ai_toggle_btn = button("AI 작업 공간", w._toggle_ai)
    w.ai_toggle_btn.setCheckable(True)
    header.addWidget(w.ai_toggle_btn)
    root.addLayout(header)

    source, source_layout = card()
    source_layout.addWidget(label("01   영상 추가", "sectionTitle"))
    input_row = QHBoxLayout()
    w.url_input = QPlainTextEdit()
    w.url_input.setAccessibleName("YouTube 영상 URL")
    w.url_input.setPlaceholderText("YouTube 링크를 붙여넣으세요. 여러 링크는 줄바꿈으로 구분합니다.")
    w.url_input.setFixedHeight(64)
    input_row.addWidget(w.url_input, 1)
    w.add_btn = button("작업 추가", w.on_add_urls)
    w.add_btn.setToolTip("Ctrl+Enter로도 목록에 추가할 수 있습니다.")
    input_row.addWidget(w.add_btn)
    source_layout.addLayout(input_row)
    shortcut = QShortcut(QKeySequence("Ctrl+Return"), w.url_input)
    shortcut.setContext(Qt.WidgetShortcut)
    shortcut.activated.connect(w.on_add_urls)
    w.add_shortcut = shortcut
    outputs = QHBoxLayout()
    outputs.addWidget(label("저장 형식"))
    w.transcript_cb = QCheckBox("자막 MD + SRT")
    w.transcript_cb.setChecked(True)
    w.transcript_cb.setToolTip("Markdown과 원문 구간·시간을 보존한 SRT를 함께 저장합니다.")
    w.audio_cb = QCheckBox("MP3")
    w.video_cb = QCheckBox("MP4")
    w.bitrate_combo = QComboBox()
    w.bitrate_combo.addItems(["128 kbps", "192 kbps", "320 kbps"])
    w.bitrate_combo.setCurrentIndex(1)
    w.bitrate_combo.setAccessibleName("MP3 음질")
    w.quality_combo = QComboBox()
    w.quality_combo.addItems(["1080p", "720p", "원본(최고화질)"])
    w.quality_combo.setAccessibleName("MP4 화질")
    for widget in (w.transcript_cb, w.audio_cb, w.video_cb):
        outputs.addWidget(widget)
    outputs.addStretch()
    source_layout.addLayout(outputs)
    w.quality_options = QWidget()
    quality_row = QHBoxLayout(w.quality_options)
    quality_row.setContentsMargins(0, 0, 0, 0)
    w.bitrate_label = label("MP3 음질")
    w.quality_label = label("MP4 화질")
    for widget in (w.bitrate_label, w.bitrate_combo, w.quality_label, w.quality_combo):
        quality_row.addWidget(widget)
    quality_row.addStretch()
    source_layout.addWidget(w.quality_options)
    folder = QHBoxLayout()
    folder.addWidget(label("저장 위치"))
    w.dir_label = QLineEdit(w.out_dir)
    w.dir_label.setReadOnly(True)
    w.dir_label.setAccessibleName("저장 폴더")
    w.dir_label.setCursorPosition(0)
    folder.addWidget(w.dir_label, 1)
    w.dir_btn = button("변경", w.on_choose_dir)
    folder.addWidget(w.dir_btn)
    w.open_dir_btn = button("폴더 열기", w.on_open_dir)
    folder.addWidget(w.open_dir_btn)
    source_layout.addLayout(folder)
    settings = QHBoxLayout()
    w.settings_summary = label("", "settingsSummary")
    w.settings_summary.setWordWrap(True)
    settings.addWidget(w.settings_summary, 1)
    w.settings_btn = button("고급 설정", w._show_settings)
    settings.addWidget(w.settings_btn)
    source_layout.addLayout(settings)
    root.addWidget(source)
    build_settings(w)

    queue, queue_layout = card()
    bar = QHBoxLayout()
    bar.addWidget(label("02   작업 목록", "sectionTitle"))
    w.queue_count = label("0개", "badge")
    bar.addWidget(w.queue_count)
    bar.addStretch()
    w.clear_done_btn = button("완료 정리", w.on_clear_done)
    w.clear_all_btn = button("전체 비우기", w.on_clear_all)
    bar.addWidget(w.clear_done_btn)
    bar.addWidget(w.clear_all_btn)
    w.start_btn = button("추출 시작", w.on_start, "start_btn")
    bar.addWidget(w.start_btn)
    queue_layout.addLayout(bar)
    w.queue_stack = QStackedWidget()
    w.queue_stack.setMinimumHeight(180)
    empty = QWidget()
    empty_layout = QVBoxLayout(empty)
    empty_layout.addStretch()
    for text, role in (("＋", "emptyIcon"), ("첫 영상을 추가해 보세요", "emptyTitle"),
                       ("링크를 추가하고 추출을 시작하면\n자막과 미디어 파일을 여기서 확인할 수 있습니다.", "muted")):
        item = label(text, role)
        item.setAlignment(Qt.AlignCenter)
        empty_layout.addWidget(item)
    empty_layout.addStretch()
    w.queue_stack.addWidget(empty)
    w.table = QTableWidget(0, 5)
    w.table.setHorizontalHeaderLabels(["영상 / URL", "상태", "진행", "상세", "저장 파일"])
    w.table.setEditTriggers(QAbstractItemView.NoEditTriggers)
    w.table.setSelectionBehavior(QAbstractItemView.SelectRows)
    w.table.setSelectionMode(QAbstractItemView.SingleSelection)
    w.table.setShowGrid(False)
    w.table.setAlternatingRowColors(True)
    w.table.setWordWrap(False)
    w.table.verticalHeader().setVisible(False)
    w.table.verticalHeader().setDefaultSectionSize(46)
    hdr = w.table.horizontalHeader()
    hdr.setSectionResizeMode(0, QHeaderView.Stretch)
    hdr.setSectionResizeMode(1, QHeaderView.Fixed)
    w.table.setColumnWidth(1, 90)
    hdr.setSectionResizeMode(2, QHeaderView.Fixed)
    w.table.setColumnWidth(2, 105)
    hdr.setSectionResizeMode(3, QHeaderView.Stretch)
    # Full file paths belong in the selected-result pane, not another dense column.
    w.table.setColumnHidden(4, True)
    w.table.cellDoubleClicked.connect(w.on_row_double_clicked)
    w.table.itemSelectionChanged.connect(w._refresh_result)
    w.queue_stack.addWidget(w.table)
    queue_layout.addWidget(w.queue_stack, 1)
    w.progress = QProgressBar()
    w.progress.setObjectName("overallProgress")
    w.progress.setRange(0, 1)
    w.progress.setValue(0)
    w.progress.setTextVisible(False)
    queue_layout.addWidget(w.progress)
    root.addWidget(queue, 1)

    w.result_card, result_layout = card()
    result_header = QHBoxLayout()
    w.result_title = label("03   작업 결과", "sectionTitle")
    result_header.addWidget(w.result_title, 1)
    w.summarize_btn = button("AI 요약", w.on_ai_summarize)
    w.translate_ai_btn = button("AI 번역", w.on_ai_translate)
    result_header.addWidget(w.summarize_btn)
    result_header.addWidget(w.translate_ai_btn)
    result_layout.addLayout(result_header)
    w.result_detail = QLabel()
    w.result_detail.setTextFormat(Qt.PlainText)
    w.result_detail.setWordWrap(True)
    w.result_detail.setTextInteractionFlags(Qt.TextSelectableByMouse)
    # A scrollable detail area keeps long errors readable without growing the window.
    w.detail_scroll = QScrollArea()
    w.detail_scroll.setWidgetResizable(True)
    w.detail_scroll.setWidget(w.result_detail)
    w.detail_scroll.setFixedHeight(44)
    result_layout.addWidget(w.detail_scroll)
    w.file_combo = QComboBox()
    w.file_combo.setSizeAdjustPolicy(QComboBox.AdjustToMinimumContentsLengthWithIcon)
    w.file_combo.setMinimumContentsLength(12)
    w.file_combo.setAccessibleName("선택한 작업의 저장 파일")
    w.file_combo.currentIndexChanged.connect(
        lambda _: w.file_combo.setToolTip(w.file_combo.currentData() or ""))
    files = QHBoxLayout()
    files.addWidget(w.file_combo, 1)
    w.file_open_btn = button("파일 열기", w._open_result_file)
    w.file_folder_btn = button("파일 위치", w._open_result_folder)
    files.addWidget(w.file_open_btn)
    files.addWidget(w.file_folder_btn)
    w.file_actions = QWidget()
    w.file_actions.setLayout(files)
    files.setContentsMargins(0, 0, 0, 0)
    result_layout.addWidget(w.file_actions)
    root.addWidget(w.result_card)
    w.banner = banner_class()
    root.addWidget(w.banner)

    w.chat = chat_class(w)
    w.chat.setObjectName("chatPanel")
    w.chat.setAttribute(Qt.WA_StyledBackground, True)
    w.ai_dock = QDockWidget("AI 작업 공간", w)
    w.ai_dock.setObjectName("aiDock")
    w.ai_dock.setAllowedAreas(Qt.RightDockWidgetArea)
    w.ai_dock.setFeatures(QDockWidget.DockWidgetClosable | QDockWidget.DockWidgetFloatable)
    w.ai_dock.setWidget(w.chat)
    w.addDockWidget(Qt.RightDockWidgetArea, w.ai_dock)
    w.ai_dock.hide()
    w.ai_dock.visibilityChanged.connect(w.ai_toggle_btn.setChecked)
    for cb in (w.transcript_cb, w.audio_cb, w.video_cb, w.stt_cb):
        cb.toggled.connect(w._sync_output_controls)
    w._sync_output_controls()
    w._refresh_queue()
    w.statusBar().showMessage("준비됨 · 링크를 추가해 시작하세요")
